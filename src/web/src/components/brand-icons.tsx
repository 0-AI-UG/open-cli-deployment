// Brand marks from Simple Icons (CC0). Same props as lucide icons so they can be
// passed anywhere an icon component is expected.
import type { ReactElement, SVGProps } from "react";

type BrandIconProps = Omit<SVGProps<SVGSVGElement>, "strokeWidth"> & { size?: number; strokeWidth?: number; mono?: boolean };
export type BrandIcon = (props: BrandIconProps) => ReactElement;

function brandIcon(title: string, color: string, path: string): BrandIcon {
  // strokeWidth is accepted for lucide compatibility; brand marks are filled.
  const Icon = ({ size = 16, className = "", mono = false, strokeWidth: _strokeWidth, ...rest }: BrandIconProps) => (
    <svg role="img" aria-label={title} {...rest} viewBox="0 0 24 24" width={size} height={size} fill={mono ? "currentColor" : color} className={`shrink-0 ${className}`}>
      <path d={path} />
    </svg>
  );
  Icon.displayName = `${title.replace(/\W/g, "")}Icon`;
  return Icon;
}

