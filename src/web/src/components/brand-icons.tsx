/** Picks the logo for a Git host name, falling back to the generic Git mark. */
export function gitHostIcon(host?: string | null): BrandIcon {
  const h = (host || "").toLowerCase();
  if (h.includes("github")) return GitHubIcon;
  if (h.includes("gitlab")) return GitLabIcon;
  return GitIcon;
}
